function normalizeArray(value) {
  if (Array.isArray(value)) return value;
  if (!value) return [];
  if (typeof value === 'string') {
    try {
      const parsed = JSON.parse(value);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  }
  return [];
}

function normalizeProfile(profile) {
  if (!profile) return null;
  return { ...profile, skills: normalizeArray(profile.skills) };
}

function normalizeProject(project) {
  if (!project) return null;
  return { ...project, tags: normalizeArray(project.tags) };
}

function normalizeExperience(experience) {
  if (!experience) return null;
  return { ...experience, tags: normalizeArray(experience.tags) };
}

function getSql() {
  const databaseUrl = process.env.DATABASE_URL || process.env.POSTGRES_URL;

  if (!databaseUrl) {
    throw new Error('DATABASE_URL atau POSTGRES_URL belum diset. Hubungkan project ke Neon di Vercel Storage.');
  }

  if (!sqlClient) {
    sqlClient = neon(databaseUrl);
  }

  return sqlClient;
}

export async function ensureDatabase() {
  if (setupPromise) return setupPromise;

  setupPromise = (async () => {
    const sql = getSql();

    await sql`
      CREATE TABLE IF NOT EXISTS profile (
        id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
        name TEXT,
        role TEXT,
        bio TEXT,
        image_url TEXT,
        skills JSONB DEFAULT '[]'::jsonb,
        email TEXT,
        github TEXT,
        linkedin TEXT,
        instagram TEXT,
        location TEXT,
        years_experience INTEGER,
        hero_title TEXT,
        hero_intro TEXT,
        availability_text TEXT,
        primary_cta_label TEXT,
        primary_cta_href TEXT,
        secondary_cta_label TEXT,
        secondary_cta_href TEXT,
        about_heading TEXT,
        about_note_1 TEXT,
        about_note_2 TEXT,
        experience_summary TEXT,
        contact_heading TEXT
      )
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS projects (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        description TEXT,
        image TEXT,
        tags JSONB DEFAULT '[]'::jsonb,
        link TEXT,
        repo TEXT,
        year TEXT,
        sort_order INTEGER DEFAULT 0,
        created_at TIMESTAMPTZ DEFAULT now()
      )
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS experiences (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        company TEXT NOT NULL,
        title TEXT,
        period TEXT,
        location TEXT,
        tags JSONB DEFAULT '[]'::jsonb,
        sort_order INTEGER DEFAULT 0,
        created_at TIMESTAMPTZ DEFAULT now()
      )
    `;
  })();

  return setupPromise;
}

